// @vitest-environment node
import { readFile } from "node:fs/promises";

import { describe, expect, it } from "vitest";

import { frontendPath } from "./paths";

interface OpenApiDocument {
  paths: Record<string, Record<string, { operationId?: string }>>;
}

async function spec(): Promise<OpenApiDocument> {
  return JSON.parse(
    await readFile(frontendPath("openapi.json"), "utf8"),
  ) as OpenApiDocument;
}

describe("generated API client", () => {
  it("S0-AC-32: schema.d.ts is generated by openapi-typescript", async () => {
    const schema = await readFile(frontendPath("src/api/schema.d.ts"), "utf8");

    expect(schema).toMatch(/auto-generated by openapi-typescript/i);
  });

  it("S0-AC-32: schema.d.ts covers every path and operationId in openapi.json", async () => {
    const schema = await readFile(frontendPath("src/api/schema.d.ts"), "utf8");
    const document = await spec();

    for (const [path, item] of Object.entries(document.paths)) {
      expect(schema, path).toContain(`"${path}"`);
      for (const operation of Object.values(item)) {
        if (operation.operationId)
          expect(schema).toContain(operation.operationId);
      }
    }
  });

  it("S0-AC-32: the Stage 0 operations are in the committed spec", async () => {
    const document = await spec();

    expect(document.paths["/api/health"]?.get?.operationId).toBe("getHealth");
    expect(document.paths["/api/health/ready"]?.get?.operationId).toBe(
      "getReadiness",
    );
  });

  it("S1-AC-25: the Stage 1 operations are in the committed spec", async () => {
    const document = await spec();

    expect(document.paths["/api/receipts"]?.get?.operationId).toBe(
      "listReceipts",
    );
    expect(document.paths["/api/receipts/{receipt_id}"]?.get?.operationId).toBe(
      "getReceipt",
    );
    expect(document.paths["/api/categories"]?.get?.operationId).toBe(
      "listCategories",
    );
  });

  it("S1-AC-25: the generated client types the Stage 1 schemas", async () => {
    const schema = await readFile(frontendPath("src/api/schema.d.ts"), "utf8");

    for (const name of [
      "MoneyOut",
      "ReceiptSummaryOut",
      "ReceiptPageOut",
      "ReceiptDetailOut",
      "LineItemOut",
      "ArithmeticReportOut",
      "CategoryOut",
    ]) {
      expect(schema).toContain(`${name}: {`);
    }
  });

  it("S0-AC-32: generated files are excluded from Prettier", async () => {
    const ignore = await readFile(frontendPath(".prettierignore"), "utf8");

    expect(ignore).toContain("src/api/schema.d.ts");
    expect(ignore).toContain("openapi.json");
  });
});
